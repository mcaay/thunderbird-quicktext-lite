// Builds vendor/codemirror.js from the pinned npm packages (npm run build:vendor).
// The output is not minified, so it can be reviewed and rebuilt byte for byte.

import { build } from "esbuild";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const path = (relative) => fileURLToPath(new URL(relative, import.meta.url));
const { devDependencies } = JSON.parse(await readFile(path("../package.json"), "utf8"));
const packages = Object.entries(devDependencies)
  .filter(([name]) => name.startsWith("@codemirror/"))
  .map(([name, version]) => `${name}@${version}`)
  .join(", ");

const { metafile } = await build({
  entryPoints: [path("./codemirror-entry.js")],
  outfile: path("../vendor/codemirror.js"),
  bundle: true,
  format: "esm",
  target: "firefox128",
  minify: false,
  legalComments: "inline",
  metafile: true,
  banner: {
    js: [
      "// CodeMirror 6 for Quicktext Lite (MIT licence, https://codemirror.net).",
      "// Generated by tools/build-vendor.mjs from package-lock.json. Do not edit.",
      `// Packages: ${packages}`,
      "// Licences of all bundled packages: vendor/THIRD-PARTY-LICENSES.txt",
    ].join("\n"),
  },
});

// The MIT licence asks for its notice in every copy, and the sources carry
// none, so the licence file of every bundled package travels with the bundle.
const packageDirs = new Set();
const [bundle] = Object.values(metafile.outputs);
for (const [input, { bytesInOutput }] of Object.entries(bundle.inputs)) {
  const match = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input.replace(/\\/g, "/"));
  if (match && bytesInOutput > 0) packageDirs.add(match[1]);
}
const notices = new Map();
for (const dir of [...packageDirs].sort()) {
  const { name, version } = JSON.parse(await readFile(join(dir, "package.json"), "utf8"));
  const file = (await readdir(dir)).find((entry) => /^licen[cs]e/i.test(entry));
  if (!file) throw new Error(`${name} has no licence file`);
  const text = (await readFile(join(dir, file), "utf8")).trim();
  notices.set(text, [...(notices.get(text) ?? []), `${name}@${version}`]);
}
const sections = [...notices].map(([text, names]) => `${names.join(", ")}\n\n${text}`);
await writeFile(
  path("../vendor/THIRD-PARTY-LICENSES.txt"),
  `Packages bundled in vendor/codemirror.js and their licences.\n\n${sections.join(`\n\n${"=".repeat(72)}\n\n`)}\n`,
);
console.log(`vendor/codemirror.js built, licences of ${packageDirs.size} packages written`);
